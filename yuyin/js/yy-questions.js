  const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
  function shuffle(arr) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }

  function mk(typeId, typeName, level, stem, exprHtml, options, ansIdx, analysis, tip) {
    options.forEach((o, i) => { o.k = 'ABCD'[i]; });
    return { typeId, typeName, level, stem, exprHtml, options, ansIdx, analysis, tip };
  }

  /** 从题库条目构造题目：选项洗牌 + 动态标注正确项字母 */
  function bankQ(typeId, typeName, item) {
    const opts = shuffle(
      [{ text: item.ans, isAns: true }].concat(item.wrongs.map((w) => ({ text: w.t })))
    );
    const ansIdx = opts.findIndex((o) => o.isAns);
    const L = 'ABCD'[ansIdx];
    return mk(typeId, typeName, item.lvl, item.stem, null, opts, ansIdx, item.analysis(L), item.tip);
  }

  /** 按练习档位选题：优先匹配档位，缺题时回退全部 */
  function byLevel(bank, level) {
    const hit = bank.filter((it) => it.lvl === level);
    return hit.length ? pick(hit) : pick(bank);
  }

