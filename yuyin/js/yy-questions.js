  function genPaixu(level) {
    const item = byLevel(PAIXU, level);
    const n = item.sents.length;
    const labels = '①②③④⑤'.slice(0, n).split('');
    const display = shuffle(item.sents.map((s, i) => ({ s, i })));
    const correctSeq = item.sents.map((s) => display.findIndex((d) => d.i === item.sents.indexOf(s)));
    const correctStr = labels[correctSeq[0]] + correctSeq.slice(1).map((idx) => labels[idx]).join('');
    const seqStr = (seq) => seq.map((idx) => labels[idx]).join('');

    // 构造 3 个错误排列：相邻交换 / 首句后移 / 随机排列，保证互不相同且不等于正确答案
    const wrongs = new Set();
    for (let i = 0; i < n - 1; i++) {
      const seq = correctSeq.slice();
      [seq[i], seq[i + 1]] = [seq[i + 1], seq[i]];
      wrongs.add(seqStr(seq));
    }
    const shuffled = shuffle(correctSeq);
    if (seqStr(shuffled) !== correctStr) wrongs.add(seqStr(shuffled));
    while (wrongs.size < 3) {
      const seq = shuffle(correctSeq);
      if (seqStr(seq) !== correctStr) wrongs.add(seqStr(seq));
    }

    const stem =
      item.sents
        .map((s, i) => {
          const d = display.findIndex((x) => x.i === i);
          return `${labels[d]}${s}`;
        })
        .join('<br>') +
      `<br>以上句子排列顺序最恰当的是：`;
    const options = shuffle([
      { text: correctStr, isAns: true },
      { text: [...wrongs][0] },
      { text: [...wrongs][1] },
      { text: [...wrongs][2] },
    ]);
    const ansIdx = options.findIndex((o) => o.isAns);
    const L = 'ABCD'[ansIdx];
    const rolesTxt = item.sents.map((s, i) => `「${labels[correctSeq[i]]}」${item.roles[i]}`).join('；');
    return mk('paixu', '语句表达 · 语句排序', item.lvl, stem, null, options, ansIdx,
      `正确顺序为 <b>${correctStr}</b>，选 ${L}。<br>
       ${item.chain}<br>
       <em>各句角色：${rolesTxt}。</em>`,
      '先排首句（指代词开头、关联词后件的句子不作首句），再用指代捆绑定相邻，最后通读验证。');
  }

